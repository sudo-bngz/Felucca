"""The ALEA engine's factory bank (firmware/src/alea/alea_factory.h) from patches compiled by alea
(https://github.com/sudo-bngz/alea): each .alb in assets/alea/ holds one patch (`alea bass.alea --seed 7 --fm1
bass.alb`); they are joined, in the order given, into one ALB1 bank (alea's fm1/FORMAT.md).
  tools/gen_alea_factory.py firmware/src/alea/alea_factory.h assets/alea/{bass,pad,bell,stab}.alb"""
import struct
import sys


def patches(path):
    b = open(path, "rb").read()
    if b[:4] != b"ALB1":
        raise SystemExit(f"{path}: not an ALEA bank")
    p = 5
    for _ in range(b[4]):
        size = struct.unpack_from("<I", b, p + 16)[0]
        yield b[p:p + 20 + size]
        p += 20 + size


def main():
    out, srcs = sys.argv[1], sys.argv[2:]
    recs = [r for s in srcs for r in patches(s)]
    if not 1 <= len(recs) <= 16:
        raise SystemExit("a bank holds 1 to 16 patches")
    bank = b"ALB1" + bytes([len(recs)]) + b"".join(recs)
    if len(bank) > 3584:
        raise SystemExit(f"the bank is {len(bank)} bytes, the engine keeps 3584")
    names = ", ".join(r[:16].rstrip(b"\0").decode() for r in recs)
    rows = [", ".join(f"0x{c:02X}" for c in bank[i:i + 16]) for i in range(0, len(bank), 16)]
    with open(out, "w") as f:
        f.write("/* SPDX-License-Identifier: GPL-3.0-only\n"
                f" * generated by tools/gen_alea_factory.py from {' '.join(s.split('/')[-1] for s in srcs)}: do not edit */\n"
                f"/* the ALEA engine's factory bank (eng_alea.c): {names}; {len(bank)} bytes */\n"
                "static const uint8_t ALEA_FACTORY[] = {\n    " + ",\n    ".join(rows) + ",\n};\n")
    print(f"alea factory: {len(recs)} patches ({names}), {len(bank)} B -> {out}")


main()
